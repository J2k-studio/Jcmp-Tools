# gen_runtime.py APK -- takes classes.dex out of a makej GL apk and writes runtime.j (the Java runner, embedded in apkj)
import sys, zipfile
d = zipfile.ZipFile(sys.argv[1]).read('classes.dex')
h = d.hex()
out = ['// GENERATED by gen_runtime.py from the classes.dex of a makej apk (GlGameActivity + GameLib, compiled once with ecj and d8). Do not edit.',
       '// The Java runner of every GL page app: it loads libgame.so and hands over the screen, touch and keys.', '',
       'String rt_hex_to_bytes(String h) {', '    String r = "";', '    for i in 0..h.len / 2 {', '        int hi = h[2 * i] - 48;',
       '        int lo = h[2 * i + 1] - 48;', '        if hi > 9 { hi = hi - 39; }', '        if lo > 9 { lo = lo - 39; }',
       '        r.push((char)(hi * 16 + lo));', '    }', '    return r;', '}', '', 'String runtime_dex() {', '    String h = "";']
for i in range(0, len(h), 1000):
    out.append('    h.append("%s");' % h[i:i + 1000])
out += ['    return rt_hex_to_bytes(h);', '}', '']
open('runtime.j', 'w').write('\n'.join(out))
print(len(d), 'bytes')
